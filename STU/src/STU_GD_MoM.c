/* Total nodes reachable from all heads == the builder's count for the plane.  A node index outside [0,1600) is the list terminator
   (ST_UNDEFINED or stale); the guard bounds the walk against a corrupt cycle.  Counting by traversal means no _landmasses read. */
static int STU_GD_Count_Square_Nodes(const int16_t * heads, const int16_t * lists)
{
    int used = 0;
    int itr_landmasses = 0;
    int node = 0;
    int guard = 0;

    for(itr_landmasses = 0; itr_landmasses < NUM_LANDMASSES; itr_landmasses++)
    {
        node = heads[itr_landmasses];
        guard = 0;
        while(node >= 0 && node < STU_GD_MOM_SQUARE_NODE_LIMIT && guard++ < STU_GD_MOM_SQUARE_NODE_LIMIT)
        {
            used++;
            node = lists[node];
        }
    }
    return used;
}


/* heads for every landmass (reset every rebuild, always valid); lists/wx/wy only up to the used node count -- their tails are stale
   scratch and would diff spuriously.  Mirrors the OG capfn byte-for-byte.  Flushes per plane. */
static void STU_GD_Dump_Square_Lists(const char * point, const char * label, int16_t * const * heads, int16_t * const * lists, int8_t * const * wx_array, int8_t * const * wy_array)
{
    int wp = 0;
    int used = 0;

    for(wp = 0; wp < NUM_PLANES; wp++)
    {
        used = STU_GD_Count_Square_Nodes(heads[wp], lists[wp]);
        STU_GD_Dump_Chunked(point, label, wp, ".heads", heads[wp], GD_I16, NUM_LANDMASSES);
        STU_GD_Dump_Chunked(point, label, wp, ".lists", lists[wp], GD_I16, used);
        STU_GD_Dump_Chunked(point, label, wp, ".wx_array", wx_array[wp], GD_I8, used);
        STU_GD_Dump_Chunked(point, label, wp, ".wy_array", wy_array[wp], GD_I8, used);
        STU_Log_Flush_All();   /* drain per plane -- avoid async-logger ring overrun */
    }
}


