/* 603/610/611: s_LANDMASSES { uint8 wx_array[60], uint8 wy_array[60], int8 type_array[60] } per (plane, player);
   flat record idx = plane * NUM_NONNPC_PLAYERS + player.  No flush (as the original). */
void STU_GD_Dump_AI_Continents(const char * point)
{
    char buf[STU_GD_MOM_ROW_BUF_SIZE];
    int wp = 0;
    int itr_players = 0;
    int flat = 0;

    for(wp = 0; wp < NUM_PLANES; wp++)
    {
        for(itr_players = 0; itr_players < NUM_NONNPC_PLAYERS; itr_players++)
        {
            flat = (wp * NUM_NONNPC_PLAYERS) + itr_players;
            STU_GD_Format_Csv(buf, (int)sizeof(buf), _ai_continents.plane[wp].player[itr_players].wx_array, GD_U8, 0, NUM_LANDMASSES);
            STU_GD_WRITE("[GD] %s _ai_continents[%d].wx_array = %s", point, flat, buf);
            STU_GD_Format_Csv(buf, (int)sizeof(buf), _ai_continents.plane[wp].player[itr_players].wy_array, GD_U8, 0, NUM_LANDMASSES);
            STU_GD_WRITE("[GD] %s _ai_continents[%d].wy_array = %s", point, flat, buf);
            STU_GD_Format_Csv(buf, (int)sizeof(buf), _ai_continents.plane[wp].player[itr_players].type_array, GD_I8, 0, NUM_LANDMASSES);
            STU_GD_WRITE("[GD] %s _ai_continents[%d].type_array = %s", point, flat, buf);
        }
    }
}
