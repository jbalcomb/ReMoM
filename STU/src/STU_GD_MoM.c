/* _HEROES2 is NUM_PLAYERS pointers, one s_HEROES { s_HERO heroes[NUM_HERO_TYPES]; } per player, so it is not one contiguous array:
   dump each allocated player's block as one record (heroes_fields is the flattened heroes[0..34].<field> map). */
void STU_GD_Dump_Heroes(const char * point)
{
    int itr_players = 0;

    for(itr_players = 0; itr_players < NUM_PLAYERS; itr_players++)
    {
        if(_HEROES2[itr_players] == NULL)
        {
            continue;   /* unallocated player slot */
        }
        STU_GD_Dump_Record(point, "_HEROES2", itr_players, _HEROES2[itr_players], heroes_fields, HEROES_FIELD_COUNT);
    }
}


